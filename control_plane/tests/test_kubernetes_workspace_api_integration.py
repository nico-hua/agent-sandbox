REFERENCE = 'docker.io/library/agent-sandbox-basic:dev'


def _cached_manifest_digest():
    """Read the cached image target, then hash its actual manifest/index bytes; never use its config ID."""
    prefix = ['minikube', '-p', 'agent-sandbox-k8s', 'ssh', '--node=agent-sandbox-k8s', '--']
    result = subprocess.run(prefix + ['sudo', 'ctr', '--namespace', 'k8s.io', 'images', 'ls', 'name==' + REFERENCE],
                            capture_output=True, text=True, timeout=20)
    assert result.returncode == 0, 'cached project image target unavailable'
    rows = [line.split() for line in result.stdout.splitlines() if line.split()[:1] == [REFERENCE]]
    assert len(rows) == 1 and len(rows[0]) >= 3, 'cached project image target is ambiguous'
    assert rows[0][1] in {
        'application/vnd.docker.distribution.manifest.v2+json',
        'application/vnd.docker.distribution.manifest.list.v2+json',
        'application/vnd.oci.image.manifest.v1+json', 'application/vnd.oci.image.index.v1+json',
    }, 'cached target is not a content manifest/index'
    digest = rows[0][2]
    assert re.fullmatch(r'sha256:[0-9a-f]{64}', digest), 'cached target digest invalid'
    # Only this strictly validated hex digest enters the trusted remote command.
    # Hash on the node to avoid SSH terminal newline transformations of content.
    checked = subprocess.run(prefix + ['sudo ctr --namespace k8s.io content get ' + digest + ' | sha256sum'],
                             capture_output=True, text=True, timeout=20)
    assert checked.returncode == 0 and checked.stdout.split()[:1] == [digest[7:]], 'manifest content digest mismatch'
    return digest


class RecordingCore:
    """Capture the real Service-created identity and original POST UID solely for independent fixture cleanup."""

    def __init__(self, api, namespace, digest, originals):
        """Borrow a worker-owned connection pool; never synthesize database state or close another pool."""
        self.api, self.namespace, self.digest, self.originals = api, namespace, digest, originals

    def __getattr__(self, key):
        """Delegate to the actual Kubernetes facade, including its worker-owned api_client handle."""
        return getattr(self.api, key)

    def create_namespaced_persistent_volume_claim(self, namespace, body, **kwargs):
        """Record only metadata actually generated by the public Service and the resulting original API response."""
        assert namespace == self.namespace and not self.originals
        labels, annotations = body.metadata.labels, body.metadata.annotations
        wid = labels[PREFIX + 'workspace-id']
        record = WorkspaceRecord(wid, labels[PREFIX + 'workspace-token'], 'agent-sandbox-' + wid,
            annotations[PREFIX + 'workspace-image-id'], datetime.fromisoformat(annotations[PREFIX + 'created-at']))
        assert record.image_id == self.digest
        receipt = {'submitted': True, 'uid': None}
        self.originals.append((record, receipt))
        pvc = self.api.create_namespaced_persistent_volume_claim(namespace, body, **kwargs)
        receipt['uid'] = _owned(pvc, record, namespace, None)
        return pvc


@pytest.fixture
def public_workspace_target():
    """Resolve only the explicit existing target after opt-in and independently clean original POST identities."""
    path = Path(os.environ.get('KUBERNETES_TEST_KUBECONFIG', str(Path.home() / '.kube' / 'config')))
    namespace, context = os.environ['KUBERNETES_TEST_NAMESPACE'], os.environ['KUBERNETES_TEST_CONTEXT']
    digest = _cached_manifest_digest()
    factory = runtime_module.create_probe_client
    cleanup_api = factory(kubeconfig_path=path, context=context)
    originals = []
    try:
        assert cleanup_api.read_namespace(namespace, _request_timeout=(0.5, 1)).metadata.name == namespace
        storage = client.StorageV1Api(cleanup_api.api_client).read_storage_class(SC, _request_timeout=(0.5, 1))
        assert storage.provisioner == 'hostpath.csi.k8s.io'
        assert storage.volume_binding_mode == 'WaitForFirstConsumer' and storage.reclaim_policy == 'Delete'
        yield path, namespace, context, digest, factory, cleanup_api, originals
    finally:
        primary = sys.exc_info()[1]
        try:
            for record, receipt in originals:
                _cleanup(cleanup_api, record, namespace, receipt)
        except BaseException:
            if primary is not None:
                primary.add_note('independent public workspace cleanup did not confirm absence')
            else:
                raise
        finally:
            cleanup_api.api_client.close()


@pytest.mark.anyio
async def test_formally_configured_public_workspace_create_get_delete(public_workspace_target, tmp_path, monkeypatch):
    """Accept a public POST with real manifest identity, persist its original UID, then manage it after app rebuild."""
    path, namespace, context, digest, factory, cleanup_api, originals = public_workspace_target
    for name in ('PYTHON', 'NODE'):
        monkeypatch.delenv('AGENT_SANDBOX_K8S_' + name + '_IMAGE', raising=False)
    for key, value in {
        'AGENT_SANDBOX_RUNTIME': 'kubernetes', 'AGENT_SANDBOX_K8S_KUBECONFIG': str(path),
        'AGENT_SANDBOX_K8S_CONTEXT': context, 'AGENT_SANDBOX_K8S_NAMESPACE': namespace,
        'AGENT_SANDBOX_K8S_AGENT_IMAGE': REFERENCE + '@' + digest,
        'AGENT_SANDBOX_K8S_PROXY_IMAGE': 'agent-sandbox-proxy-upstream-test:dev',
        'AGENT_SANDBOX_K8S_WORKSPACE_STORAGE_CLASS': SC,
    }.items():
        monkeypatch.setenv(key, value)

    def observed_factory(**kwargs):
        """Wrap real lazy worker pools only to preserve independent original UID cleanup evidence."""
        return RecordingCore(factory(**kwargs), namespace, digest, originals)

    monkeypatch.setattr(runtime_module, 'create_probe_client', observed_factory)
    database = tmp_path / 'public-workspace.sqlite3'
    admin = secrets.token_urlsafe(32)
    headers = {'Authorization': 'Bearer ' + admin}
    app = create_app(api_key=admin, database_path=database, reaper_enabled=False)
    async with app.router.lifespan_context(app):
        async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url='http://control') as caller:
            assert (await caller.post('/v1/workspaces', json={})).status_code == 401
            response = await caller.post('/v1/workspaces', headers=headers, json={'environment': 'basic'})
            assert response.status_code == 201
            body = response.json()
            assert set(body) == {'workspace_id', 'status', 'sandbox_id', 'created_at'}
            assert body['status'] == 'available' and len(originals) == 1
            record, original = originals[0]
            assert body['workspace_id'] == record.workspace_id
            store = SQLiteLifecycleStore(database)
            saved = await store.get_workspace(record.workspace_id)
            receipt = await store.get_workspace_receipt(record.workspace_id, record.creation_token, expected_version=1)
            assert saved.image_id == receipt.image_id == digest and receipt.pvc_uid == original['uid']
            pvc = cleanup_api.read_namespaced_persistent_volume_claim(receipt.pvc_name, namespace, _request_timeout=(0.5, 1))
            assert pvc.status.phase == 'Pending' and pvc.spec.volume_name in (None, '')
    # Rebuild through the same formal configuration with a different current image;
    # GET/DELETE must depend on the saved original receipt, not image resolution.
    monkeypatch.setenv('AGENT_SANDBOX_K8S_AGENT_IMAGE', 'agent-sandbox-basic:dev')
    rebuilt = create_app(api_key=admin, database_path=database, reaper_enabled=False)
    route = '/v1/workspaces/' + record.workspace_id
    async with rebuilt.router.lifespan_context(rebuilt):
        async with httpx.AsyncClient(transport=httpx.ASGITransport(app=rebuilt), base_url='http://control') as caller:
            assert (await caller.get(route, headers=headers)).status_code == 200
            assert (await caller.delete(route, headers={'Authorization': 'Bearer incorrect-test-key'})).status_code == 401
            assert (await caller.delete(route, headers=headers)).status_code == 204
            assert (await caller.delete(route, headers=headers)).status_code == 204
            assert (await caller.get(route, headers=headers)).status_code == 404
    assert await SQLiteLifecycleStore(database).get_workspace(record.workspace_id) is None
    assert cleanup_api.read_namespace(namespace, _request_timeout=(0.5, 1)).metadata.name == namespace
    with pytest.raises(client.ApiException) as gone:
        cleanup_api.read_namespaced_persistent_volume_claim(receipt.pvc_name, namespace, _request_timeout=(0.5, 1))
    assert gone.value.status == 404
